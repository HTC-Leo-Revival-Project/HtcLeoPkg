#!/bin/bash
# based on the instructions from edk2-platform
set -e
export PACKAGES_PATH=$PWD/../edk2:$PWD/../edk2-platforms:$PWD
export WORKSPACE=$PWD/workspace

AvailablePlatforms=("Leo" "Schubert" "Passion" "All")
IsValid=0

# --emu: build the emulator workarounds.  When cLK hands over to the payload the
# AP generic timer is not running, and nothing in this package enables it, so
# every MicroSecondDelay()/NanoSecondDelay() busy-waits forever and the first
# driver that asks for a delay (ClockDxe) hangs.  With this flag SEC starts the
# timer itself.  Hardware builds leave it out: there the timer is already up.
EMU=0
# --screen: build for real hardware: the debug output goes to the framebuffer
# instead of the UART (a phone has no UART to read) and NandDxe stops after its
# self test so the result can be read off the screen.
SCREEN=0
_rest=()
for arg in "$@"; do
    case "${arg}" in
        --emu) EMU=1 ;;
        --screen) SCREEN=1 ;;
        *) _rest+=("${arg}") ;;
    esac
done
if [ ${#_rest[@]} -gt 0 ]; then
    set -- "${_rest[@]}"
else
    set --
fi
if [ "${EMU}" = 1 ]; then
    export EMU_WORKAROUND=1
fi

# Hand the switch to the firmware as a generated header: the DSC macro route
# does not pick up exported environment variables, and SEC has to know whether
# to start the AP generic timer itself.
mkdir -p QSD8250Pkg/Include/Library
# NAND_SELFTEST=1 lets NandDxe erase, program, read back and erase again one
# block, which throws away whatever is in it.  It follows --emu (the emulator's
# NAND image has a spare block at the end); set it in the environment to choose
# a different block on real hardware, e.g.
#   NAND_SELFTEST=1 NAND_SELFTEST_BLOCK=4094 ./build.sh -d Leo
NAND_SELFTEST=${NAND_SELFTEST:-$EMU}
NAND_SELFTEST_BLOCK=${NAND_SELFTEST_BLOCK:-0xFFFFFFFF}
cat > QSD8250Pkg/Include/Library/EmuWorkaround.h <<EOF
/** @file
  Generated by build.sh (--emu: ${EMU}, --screen: ${SCREEN}) - do not edit.
  1 = emulator build: cLK leaves the AP generic timer stopped, so SEC starts it.

  NAND_SELFTEST       = 1: let NandDxe run its destructive self test.
  NAND_SELFTEST_BLOCK = block to use for it, 0xFFFFFFFF = the last block.
  HALT_AFTER_SELFTEST = 1: stop the firmware after the self test.
**/
#ifndef EMU_WORKAROUND_H
#define EMU_WORKAROUND_H

#define EMU_WORKAROUND ${EMU}
#define NAND_SELFTEST ${NAND_SELFTEST}
#define NAND_SELFTEST_BLOCK ${NAND_SELFTEST_BLOCK}
#define HALT_AFTER_SELFTEST ${SCREEN}

#endif // EMU_WORKAROUND_H
EOF

while getopts d: flag
do
    case "${flag}" in
        d)
			device=${OPTARG}
			;;
    esac
done

function _check_args() {
	local DEVICE="${1}"
	for Name in "${AvailablePlatforms[@]}"
	do
		if [ "${DEVICE}" == "${Name}" ]
		then
			IsValid=1
			break;
		fi
	done
}

function _clean() {
	for PlatformName in "${AvailablePlatforms[@]}"
	do
		if [ "${PlatformName}" != "All" ]; then
			rm -f "ImageResources/${PlatformName}/bootpayload.bin"
			rm -f "ImageResources/${PlatformName}/os.nb"
			rm -f "ImageResources/${PlatformName}/uefi.img"
			rm -f "ImageResources/${PlatformName}/"*.nbh
		fi
	done
	rm -f "ImageResources/Leo/nbgen"
	rm -f "ImageResources/Leo/yangbin"
	rm -f "BootShim/BootShim."{bin,elf}
	rm -rf "workspace/Build"
	echo "Artifacts removed"
}

function _patch_edk() {
	echo "Patching EDK2 Source"

	PATCH1_APPLIED=0
	PATCH2_APPLIED=0

	file="../edk2/BaseTools/Source/C/GenFw/Elf32Convert.c"
	# Check if R_ARM_PC13 already exists
	if ! grep -q "case R_ARM_PC13:" "${file}"
	then
		# Insert after R_ARM_REL32
		sed -i '/case R_ARM_REL32:/a\        case R_ARM_PC13:' "${file}"
		echo "Inserted 'case R_ARM_PC13:' after 'case R_ARM_REL32:'."
		PATCH1_APPLIED=1
	else
		echo "'case R_ARM_PC13:' already exists. No changes made."
	fi


	file="../edk2/MdeModulePkg/Universal/Disk/UnicodeCollation/EnglishDxe/UnicodeCollationEng.c"
	# Use sed to replace only if the "Status;" version exists
	if grep -q "EFI_STATUS  Status;" "${file}"
	then
		sed -i 's/EFI_STATUS  Status;/EFI_STATUS  Status = EFI_SUCCESS;/' "${file}"
		echo "Replaced 'EFI_STATUS  Status;' with 'EFI_STATUS  Status = EFI_SUCCESS;'"
		PATCH2_APPLIED=1
	else
		echo "Pattern not found, no changes made."
	fi

	if [ ${PATCH1_APPLIED} -eq 1 ] && [ ${PATCH2_APPLIED} -eq 1 ]
	then
		echo "Both patches applied successfully."
	fi
}

# based on https://github.com/edk2-porting/edk2-msm/blob/master/build.sh#L47 
function _build() {
	local DEVICE="${1}"
	shift

	# NBH creation
	if [ ! -f ImageResources/Leo/nbgen ]; then
		gcc -std=c99 ImageResources/Leo/nbgen.c -o ImageResources/Leo/nbgen
		if [ $? -ne 0 ]
		then
			echo "Failed to build nbgen" 1>&2
			return 1
		fi
	fi
	# We're using a prebuild yang binary for now, since the compiled version doesn't seem to produce a valid NBH for Leo
	if [ ! -f ImageResources/Leo/yang ]; then
		gcc ImageResources/Leo/yang_src/nbh.c ImageResources/Leo/yang_src/nbhextract.c ImageResources/Leo/yang_src/yang.c -o ImageResources/Leo/yang
		if [ $? -ne 0 ]
		then
			echo "Failed to build yang" 1>&2
			return 1
		fi
	fi

	make -C BootShim UEFI_BASE=0x2C000000 UEFI_SIZE=0x00100000
	if [ $? -ne 0 ]
	then
		echo "Failed to build BootShim" 1>&2
		return 1
	fi

	source "../edk2/edksetup.sh"

	NUM_CPUS=$((`getconf _NPROCESSORS_ONLN` + 2))

	# The debug output goes to the UART on the emulator and to the framebuffer on
	# real hardware, which has no UART to speak of.  Either way a --screen build
	# stops in NandDxe after its self test so the output stays readable.
	DSCOPTS=()
	if [ "${SCREEN}" = 1 ]; then
		DSCOPTS=(-D USE_SCREEN_FOR_SERIAL_OUTPUT=1 -D USE_UART_FOR_SERIAL_OUTPUT=0)
		echo "Debug output on the screen, UART off, halting after the NAND self test"
	else
		DSCOPTS=(-D USE_SCREEN_FOR_SERIAL_OUTPUT=0 -D USE_UART_FOR_SERIAL_OUTPUT=1)
	fi

	# BaseTools only has to be built once.  Cleaning it on every run costs
	# minutes and buys nothing, so only do that when asked for.
	if [ -n "$REBUILD_BASETOOLS" ]
	then
		make clean -C ../edk2/BaseTools
		make -C ../edk2/BaseTools -j$(nproc)
	elif [ ! -x ../edk2/BaseTools/Source/C/bin/VfrCompile ] || [ ! -x ../edk2/BaseTools/Source/C/bin/GenFw ]
	then
		make -C ../edk2/BaseTools -j$(nproc)
	else
		echo "BaseTools present, skipping (REBUILD_BASETOOLS=1 to force)"
	fi

	platforms=()

	if [ "${DEVICE}" == 'All' ]
	then
		for PlatformName in "${AvailablePlatforms[@]}"
		do
			if [ "${PlatformName}" != 'All' ]
			then
				platforms+=("${PlatformName}")
			fi
		done
	else
		platforms+=("${DEVICE}")
	fi

	for PlatformName in "${platforms[@]}"
	do
		echo "Building uefi for ${PlatformName}"
		build -n "${NUM_CPUS}" -a ARM -t CLANGDWARF -p "Platforms/Htc${PlatformName}/Htc${PlatformName}Pkg.dsc" -b DEBUG "${DSCOPTS[@]}"

		./build_boot_images.sh "${PlatformName}"
	done
}

_check_args "${device}"
if [ $IsValid == 1 ]
then
	_clean
	_patch_edk
	_build "${device}"
else
	echo "Build: Invalid platform"
	echo "Available targets: "
	for Name in "${AvailablePlatforms[@]}"
	do
		echo " - ${Name}"
	done
fi
